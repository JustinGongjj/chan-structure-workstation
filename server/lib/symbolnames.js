let futuresTags = null;
function getFuturesTags() {
  if (futuresTags) return futuresTags;
  futuresTags = {};
  try {
    const S = require('./sectors');
    const cat = S.catalog ? S.catalog() : [];
    for (const g of cat) for (const it of (g.items || [])) futuresTags[it.code] = [g.name, '期货'];
  } catch (e) { /* 忽略 */ }
  return futuresTags;
}

function tagsOf(market, code) {
  const m = String(market || '').toUpperCase();
  const c = String(code || '');
  if (m === 'CNF' || m === 'USF') return getFuturesTags()[c] || ['期货', ''];
  const t = (TAGS[m] && TAGS[m][c]) || [];
  return t.length ? t : ['', ''];
}

/* 市场名称统一从 constants 取 */
const MARKET_LABEL = require('./constants').MARKETS;

/** 取中文名；期货回退到 sectors 目录 */
let futuresNames = null;
function getFuturesNames() {
  if (futuresNames) return futuresNames;
  futuresNames = {};
  try {
    const S = require('./sectors');
    const cat = S.catalog ? S.catalog() : [];
    for (const g of cat) for (const it of (g.items || [])) futuresNames[it.code] = it.name;
  } catch (e) { /* 忽略 */ }
  return futuresNames;
}

function nameOf(market, code) {
  const m = String(market || '').toUpperCase();
  const c = String(code || '');
  if (m === 'CNF' || m === 'USF') return getFuturesNames()[c] || c;
  return (NAMES[m] && NAMES[m][c]) || c;
}

/** 带名称的完整标的池 */
function universeWithNames(items) {
  return items.map((x) => {
    const tg = tagsOf(x.market, x.code);
    return {
      market: x.market,
      code: x.code,
      name: nameOf(x.market, x.code),
      marketLabel: MARKET_LABEL[x.market] || x.market,
      sector: tg[0] || '',
      style: tg[1] || '',
      key: x.market + ':' + x.code,
    };
  });
}

module.exports = { nameOf, universeWithNames, tagsOf, NAMES, TAGS, MARKET_LABEL };
